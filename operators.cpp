#include <iostream>
#include <bits/stdc++.h>

using namespace std;

int main()
{

    int a = 5, b = 10;
    cout << a & b << endl;
    cout << a | b << endl;
    cout << a ^ b << endl;
    cout << a++ + ++a << endl;
    cout << a-- - --a << endl;
    cout << b++ + ++b << endl;
    cout << b-- - --b << endl;
    cout << a && b << endl;

    return 0;
}